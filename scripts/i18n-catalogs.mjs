#!/usr/bin/env node
// Generates package/contents/ui/logic/Catalogs.js from translations/*.po, so the widget can
// switch language at runtime (KDE's i18n() always follows the system language).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "package/contents/ui/logic/Catalogs.js");

function unquote(s) {
  return JSON.parse(s.replace(/\\(?!["\\nt])/g, "\\\\"));
}

export function parsePo(text) {
  const entries = [];
  for (const block of text.split(/\n\s*\n/)) {
    const lines = block.split("\n");
    if (lines.some((l) => l.startsWith("#, ") && l.includes("fuzzy"))) {
      continue;
    }
    const e = {};
    let key = null;
    for (const l of lines) {
      if (l.startsWith("#")) continue;
      const m = /^(msgctxt|msgid_plural|msgid|msgstr(?:\[\d+\])?)\s+(".*")$/.exec(l);
      if (m) {
        key = m[1];
        e[key] = unquote(m[2]);
      } else if (key && /^".*"$/.test(l)) {
        e[key] += unquote(l);
      }
    }
    if ("msgid" in e) entries.push(e);
  }
  return entries;
}

function build() {
  const dir = path.join(root, "translations");
  const langs = fs.readdirSync(dir).filter((f) => f.endsWith(".po")).sort();
  let out = ".pragma library\n\n"
    + "// GENERATED by scripts/i18n-catalogs.mjs from translations/*.po. Do not edit.\n"
    + "// key: msgid, or msgctxt + \"\\u0004\" + msgid; value: string, or array of plural forms.\n\n"
    + "var CATALOGS = {\n";
  langs.forEach((file, li) => {
    const code = path.basename(file, ".po");
    const entries = parsePo(fs.readFileSync(path.join(dir, file), "utf8"));
    const header = (entries.find((e) => e.msgid === "") || {}).msgstr || "";
    const pm = /plural=([^;\n]+)/.exec(header);
    const plural = pm ? pm[1].trim() : "(n != 1)";
    if (!/^[n0-9\s()<>=!&|?:%+-]+$/.test(plural)) {
      throw new Error(`${file}: unexpected plural expression ${plural}`);
    }
    const messages = {};
    for (const e of entries) {
      if (e.msgid === "") continue;
      const key = (e.msgctxt !== undefined ? e.msgctxt + "\u0004" : "") + e.msgid;
      if (e.msgid_plural !== undefined) {
        const forms = Object.keys(e).filter((k) => k.startsWith("msgstr[")).sort().map((k) => e[k]);
        if (forms.every((f) => f !== "")) messages[key] = forms;
      } else if (e.msgstr) {
        messages[key] = e.msgstr;
      }
    }
    const keys = Object.keys(messages).sort();
    out += `    ${JSON.stringify(code)}: {\n`
      + `        plural: function (n) { return Number(${plural}); },\n`
      + "        messages: {\n"
      + keys.map((k) => `            ${JSON.stringify(k)}: ${JSON.stringify(messages[k])}`).join(",\n")
      + "\n        }\n"
      + `    }${li < langs.length - 1 ? "," : ""}\n`;
  });
  out += "};\n";
  fs.writeFileSync(OUT, out);
  console.log(`Wrote ${path.relative(root, OUT)} (${langs.length} language(s))`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) build();
